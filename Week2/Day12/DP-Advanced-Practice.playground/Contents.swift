/*:
 ---
 * 1. 상태 정의 다음에 반드시 해야 하는 질문 5개
 ---
 */
/// "dp[i] = 0...i까지 봤을 때 얻을 수 있는 최대 점수"
///
/// 체크리스트
/// 1. 이 상태로 정답을 바로 말할 수 있는가?
///     : dp[n][?] 중 최댓값 <- 이런 상태는 설계가 덜 됐을 확률 높음
/// 2. 이 상태가 기억해야 할 정보는 '최소'인가?
///     : 과거 선택 전체 ❌
///     : 최종 결과에 필요한 요약 정보 ⭕️
/// 3. 이 상태는 과거 한 지점만 보면 충분한가?
///     : 충분함 -> 1D 가능성 높음
///     : 여러 과거를 동시에 본다 -> 최적화/누적 고려
/// 4. 불가능한 경우가 존재하는가?
///     : 있다 -> sentinel 필요
/// 5. 이 상태 수는 입력 크기만큼만 증가하는가?
///     : YES -> 보통 O(N)
///     : NO  -> 차원/전이 재검토 신호
/*:
 ---
 * 2. 전이의 본질: 과거 중 하나를 고른다
 ---
 */
/// "현재 상태는 과거 상태 중 하나를 골라서 만들어진다."
/// 가장 기본적인 전이 형태:
///     dp[i] = max / min / sum of (da[j] + something) where j < i
///     문제의 핵심 - j를 전부 봐야 하느냐?
/*:
 ---
 * 3. O(N^2)이 생기는 정확한 이유
 ---
 */
/// 상황: i는 0부터 N까지, 매 i마다 j를 0부터 i-1까지 전부 확인
///         계산 횟수: 1 + 2 + 3 + ... N = O(N^2)
/// 전이 최적화를 관통하는 질문:
///     j를 전부 안 보고도 내가 원하는 정보를 들고 갈 수 있는가?
/*:
 ---
 * 4. 전이 최적화의 첫 번째: 누적해서 들고 가기
 ---
 */
/// 핵심사고:
///       j를 하나하나 다시 보지 말고, '지금까지의 최선'을 미리 저장하자
/// 사고흐름:
///     dp[i]는 이전 dp들 중 최선 + 현재 값이다.
///     그렇다면:
///     이전 dp의 최선을 계속 들고 가면 된다.
/// 결과:
///     j 루프 제거
///     O(N^2) -> O(N)
/*:
 ---
 * 5. 불가능 상태 처리: DP가 망가지는 주범
 ---
 */
/// 왜 필요한가?
/// DP는 모든 상태가 값이 있다고 가정하면 잘못된 전이가 생김
///
/// 예시 사고:
/// - 어떤 조건을 만족 못 하면 그 상태는 존재하지 않음
/// - 그런데 그걸 0으로 두면?
///     -> 존재하지 않는 경로가 좋은 경로처럼 취급됨
///
/// 불가능한 상태:
/// - 예1. 아직 아무것도 고르지 않았는데 3개를 이미 선택한 상태
/// - 예2. 비용 제한을 초과했는데 유효한 상태처럼 취급되는 경우
/// 👉 이런 상태라도 DP 배열에는 값이 들어가야함
///
/// 해결 전략:
/// - 최댓값 DP
///     예. dp[i] = max(후보1, 후보2, 후보3, ...)
///         이때 불가능한 후보는 정상 후보보다도 무조건 작아야함(선택되면 안되므로)
///         불가능한 상태 = 아주 작은 값 (Int.min 등)
/// - 최솟값 DP
///     예. dp[i] = min(후보1, 후보2, 후보3, ...)
///         이때 불가능한 후보는 정상 후보보다도 무조건 커야함(선택되면 안되므로)
///         불가능한 상태 = 아주 큰 값 (Int.max 등)
/*:
 ---
 * 6. 1D의 압축 조건
 ---
 */
/// 조건: dp[i]가 오직 이전 인덱스들만 참조한다
/// 사고 질문:
///     나는 이 상태를 계산할 때, i-1값만 있으면 충분한가?
///     YES:
///         - prev, cur 또는 한 배열
/*:
 ---
 * 7. 모듈러 연산은 수학이 아니라 안전장치
 ---
 */
/// DP에서 모듈로는 보통:
///     1. 경우의 수
///     2. 조합
///     3. 누적 합
/// 반드시 기억할 2줄:
///     - 덧셈: (a + b) % MOD
///     - 뺄셈: (a - b + MOD) % MOD
/// 왜?
///     중간 계산에서 음수/overflow가 나와도 결과를 항상 0 ~ MOD-1로 고정
///
/// 정답을 1,000,000,007로 나눈 나머지를 출력하라
/// 이때 MOD = 1_000_000_007
/*:
 ---
 * 8. 점화식 검증 체크리스트
 ---
 */
/// 1. 상태를 문장으로 말할 수 있는가
/// 2. 전이가 그 문장을 정확히 구현하는가
/// 3. 불가능한 상태가 섞이지 않는가
/// 4. 초기 상태는 실제 가능한가
/// 5. i / j 범위가 어긋나지 않는가
/// 6. 시간복잡도가 제한 안에 드는가
/// 7. 공간을 줄일 수 있는 구조인가
/// 8. (필요 시) 모듈러 안전한가
/*:
 ---
 * 9. 점화식 최적화/모듈러 처리 연습
 ---
 */
/// 문제
/// 길이가 N인 수열이 있다.
/// 각 칸에는 점수가 적혀 있다.
///
/// 규칙은 다음과 같다:
/// - 0번부터 N-1번까지 차례대로 본다
/// - i번째 칸을 선택하면,
/// - i보다 이전 칸 중 하나를 마지막으로 선택한 상태여야 한다
/// - 단, 아무 것도 선택하지 않은 상태에서 바로 선택해도 된다
///
/// 목표
/// 가능한 선택 방법 중에서 총 점수의 최댓값을 구하라.
///
/// 입력 형식
/// 정수 N (1 ≤ N ≤ 200,000)
/// 길이 N의 정수 배열 A
///   * A[i]는 i번째 칸의 점수
///   * -10^9 ≤ A[i] ≤ 10^9
///
/// 출력 형식
/// 가능한 선택 방법 중 최대 점수
///
/// -----------------------------------------
///
/// 1. dp[i] 상태정의
///     마지막으로 선택한 수가 i일 때 얻을 수 있는 최댓값
/// 2. 점화식
///     dp[i] = max(dp[i-1] + A[i], A[i])
/// 3. 시간 복잡도
///     O(N^2)인것 같은 느낌?
/// 4. 최적화 가능성
///     최댓값을 항상 이전값과 비교해야하는가?
///         -> 최댓값을 변수로 들고있는다면?
/// 5. 만약 줄일 수 있다면?
///     최댓값 변수를 업데이트한다.
///     dp[i] = best + A[i]
///     best = max(dp[i], best)
///     => O(N)이 보장됨
///     
