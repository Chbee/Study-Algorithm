/// "그래프에서 두 정점 사이의 최소 비용 경로를 찾는 문제."
///
/// 1. 입력 그래프: 방향/무방향, 가중치 유무
/// 2. 목표: 최소 거리(또는 최소 간선 수)
/// 3. 제약: 음수 가중치/사이클 여부
///
/// : 정점 A → 정점 B로 갈 때 이동 비용(가중치)의 합이 최소가 되는 경로를 찾는 문제
/*:
 ---
 * 2. 알고리즘 유형
 ---
 */
/// ① Dijkstra (다익스트라)
/// : 가장 대표적인 최단 경로 알고리즘
/// 특징
/// - 시작 정점 1개 → 모든 정점까지의 최단 거리
/// - 가중치가 음수일때 사용 불가
/// - 그리디 기반
/// 선택 기준
/// - 도로 길이, 시간, 비용 등 모두 양수
/// - “A에서 출발해서 모든 곳까지 최소 비용”
/// 시간 복잡도
/// - O(E log V)
/// ② Floyd–Warshall (플로이드)
/// : 모든 정점 쌍 최단 경로
/// 특징
/// - 모든 정점 i → j 최단 거리
/// - 음수 가중치 가능 (단, 음수 사이클은 안됨)
/// - DP 기반
/// 선택 기준
/// - 정점 수가 적음 (보통 ≤ 400)
/// - “모든 도시 간 최단 거리 필요”
/// 시간 복잡도
/// - O(N³) 사용에 주의 필요
/// ③ GraphSearch
/// 특징
/// - 조건부로 사용 가능
/// - BFS / DFS 기반 탐색
/// 선택 기준
/// - 모든 간선의 비용이 동일할 때 (보통 1)
/// - 미로, 격자 이동 문제
/// 시간 복잡도
/// -
/*:
 ---
 * 3. 최단 경로 알고리즘 선택 기준
 ---
 */
/// 1) 간선 가중치가 모두 동일한가?
///    - YES → BFS
///
/// 2) 간선 가중치가 존재하는가?
///    - YES, 모든 가중치 ≥ 0 → Dijkstra (우선순위 큐)
///
/// 3) 음수 가중치가 존재하는가?
///    - YES → Floyd-Warshall 고려
///
/// 4) 모든 정점 쌍의 최단 거리가 필요한가?
///    - YES → Floyd–Warshall
/*:
 ---
 * 4. BFS 핵심 흐름 (모든 간선 가중치 = 1)
 ---
 */
/// [의미]
/// - 최단 거리 = 이동 횟수
/// - 큐에 먼저 들어온 정점일수록 더 짧은 거리
///
/// [흐름]
/// 1. 거리 배열 dist를 -1로 초기화 (미방문 상태)
/// 2. 시작 정점 s에 대해 dist[s] = 0 설정 후 큐에 삽입
/// 3. 큐에서 정점을 하나 꺼냄
/// 4. 현재 정점과 인접한 정점들을 순회
/// 5. 아직 방문하지 않은 정점이라면
///    - dist[next] = dist[cur] + 1
///    - 큐에 삽입
/// 6. 큐가 빌 때까지 반복
///
/// [특징]
/// - 처음 방문한 순간의 거리가 최단 거리로 확정됨
/*:
 ---
 * 5. Dijkstra 핵심 흐름 (모든 간선 가중치 ≥ 0)
 ---
 */
/// [의미]
/// - 시작 정점으로부터의 최소 비용 경로
/// - 가장 비용이 작은 정점부터 최단 거리를 확정해 나감
///
/// [흐름]
/// 1. 거리 배열 dist를 INF로 초기화 (아직 도달 불가 상태)
/// 2. 시작 정점 s에 대해 dist[s] = 0 설정
/// 3. (현재까지의 거리, 정점) 형태로 우선순위 큐에 삽입
/// 4. 우선순위 큐에서 가장 거리가 짧은 정점을 꺼냄
/// 5. 꺼낸 거리 값이 dist[cur]보다 크면 이미 처리된 정점이므로 skip
/// 6. 현재 정점과 인접한 정점들을 순회
/// 7. 간선 완화 수행
///    - if dist[next] > dist[cur] + weight:
///        dist[next] = dist[cur] + weight
///        우선순위 큐에 삽입
/// 8. 큐가 빌 때까지 반복
///
/// [특징]
/// - 우선순위 큐에서 꺼낸 순간, 해당 정점의 최단 거리는 확정됨
/// - 음수 가중치가 있으면 이 전제가 깨짐
/*:
 ---
 * 6. Floyd–Warshall 핵심 개념 (모든 정점 쌍 최단 경로)
 ---
 */
/// [의미]
/// - 모든 정점 i → j 사이의 최단 거리 계산
/// - 특정 정점을 경유해도 되는지를 점진적으로 확장
/// - 동적 계획법(DP) 기반 알고리즘
///
/// [흐름]
/// 1. 거리 배열 dist[i][j]를 초기화
///    - i == j : 0
///    - 간선이 존재 : 해당 가중치
///    - 간선이 없음 : INF
/// 2. 중간에 거쳐갈 정점 k를 하나씩 선택
/// 3. 모든 정점 쌍 (i, j)에 대해 다음을 갱신
///    - dist[i][j] = min(
///          dist[i][j],
///          dist[i][k] + dist[k][j]
///      )
/// 4. k = 0 ~ N-1까지 반복
///
/// [특징]
/// - k번째 단계가 끝나면
///   → 정점 0~k만을 경유할 수 있을 때의 최단 거리 확정
/// - 음수 가중치는 허용되지만, 음수 사이클이 있으면 결과가 무의미
/// - 시간 복잡도는 O(N³)으로 정점 수가 작을 때만 사용 가능
