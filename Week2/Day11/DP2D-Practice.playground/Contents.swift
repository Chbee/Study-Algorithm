/// "같은 계산을 반복하지 않기 위해, 중간 결과를 저장하면서 최적값을 만든다."
///
/// 1. 상태(State): 무엇을 기억할 건가?
/// 2. 전이(Transition): 이전 상태로부터 어떻게 오는가?
/// 3. 초기값(Base Case): 가장 작은 문제는 무엇인가?
///
/// 2차원 DP는 여기서 "상태"가 2개의 축을 가지게 됨.
/*:
 ---
 * 2. 2차원 DP의 본질
 ---
 */
/// 🔹 1차원 DP
///     dp[i] = i번째까지 봤을 때의 최적값
/// 🔹 2차원 DP
///     dp[i][j] = i번째까지 봤고, j라는 조건을 만족할 때의 최적값
///         보통 i는 순서/개수, j는 선택/용량/상태/위치 같은 추가 조건
/*:
 ---
 * 3. 대표적인 상태 설계 패턴
 ---
 */
/// 패턴A: (개수x용량)
///     dp[i][w] = i번째 물건까지 고려했고, 무게 w일 때의 최대 가치
/// 패턴B: (행x열)
///     dp[i][j] = (i, j) 위치까지 왔을 때의 최적값
/// 패턴C: (길이x경우)
///     dp[i][j] = 길이 i, 상태 j일 때 가능한 경우의 수
/// 두 번째 축은 문제의 제약조건이 되는 경우가 90%.
/*:
 ---
 * 4. 아주 작은 예제로 상태 설계 연습
 ---
 */
/// 개념 연습용 문제:
/// N개의 숫자가 있다.
/// 앞에서부터 숫자를 보면서, 지금까지 선택한 숫자의 개수가 k개일 때의 최대 합을 구하라.
///
/// 1. 상태: i번째 숫자까지 봤고, k개를 선택했을 때의 최대 합
/// 2. 전이:
///     1. i번째 숫자를 선택하지 않음:
///         dp[i][j] = dp[i-1][k]
///     2. i번째 숫자를 선택함:
///         dp[i][j] = dp[i-1][k-1] + nums[i]
///     3. 최종적으로 전이는:
///         dp[i][k] = max(
///             dp[i-1][k],
///             dp[i-1][k-1] + nums[i]
///         )
/// 3. 초기값:
///     dp[0][0] = 0
///     dp[0][k>0] = 불가능
/*:
 ---
 * 5. 2차원 DP에서 자주 막히는 포인트
 ---
 */
/// 실수1: 상태 의미가 불명확함
///     dp[i][j]가 뭘 의미하는지 말로 설명 못함 -> 문장으로 설명 가능해야 함
/// 실수2: 전이가 상태 정의와 안 맞음
///     dp[i][j]인데 dp[i-2][i-1] 같은 점화식이 튀어나옴 -> 전이는 반드시 상태 정의를 존중해야함
/// 실수3: 초기값을 대충 둠
///     일단 0으로 채움 -> 2차원 DP는 불가능 상태를 명확히 해야 함
/*:
 ---
 * 6. 2차원 DP 사고 흐름 정리 (암기용)
 ---
 */
