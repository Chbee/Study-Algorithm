/// 1. i는 뭘 의미하는지? -> i
/// 2. 추가로 기억해야할 조건이 있는지? -> j
/// 3. 현재 상태로 오기 직전은 어떤 상태였는지?
/// 4. 선택/비선택, 이동 방향은 몇 가지인지?
