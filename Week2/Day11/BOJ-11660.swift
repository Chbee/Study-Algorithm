// ❌ 헷갈린점
// ============================================
/// dp 정의했는데 안맞음. 구간합을 직접 구함. N이 1024개가 최대이기 때문에 시간 초과가 발생함.
///
/// (1,1) (1,2) (1,3) (1,4)
///   a     b     c     d
/// (2,1) (2,2) (2,3) (2,4)
///   e     f     g     h
/// (3,1) (3,2) (3,3) (3,4)
///   i     j     k     l
/// (4,1) (4,2) (4,3) (4,4)
///   m     n     o     p
///
/// 이런 행렬이 있을 때 (2, 2)와 (3, 4) 사이의 부분합을 구하면
/// f+g+h+j+k+l이 구해져야함.
///
/// dp를 사용하므로 (3, 4)까지의 누적합은 a+b+c+d+...+k+l = dp[3][4]
/// 불필요한 부분을 빼야함
///
/// 우선 첫번째줄은 몽땅 필요없으므로 모두 제거.
/// 첫번째 줄의 합은 dp[1][4]이므로 -dp[y1-1][x2]
/// => e+f+g+h+...+k+l
///
/// (2, 2)보다 왼쪽에서 시작하는것이 아직 남아있음
/// 그 두개의 합은 dp[3][1]이 가지고 있으므로 -dp[y2][x1-1]
/// => f+g+h+j+k+l - a
///
/// dp[3][1]에는 a의 값도 포함되어 있음 때문에 a는 하나 더 더해줘야함
/// +dp[y1-1][x1-1]
/// => f+g+h+j+k+l
