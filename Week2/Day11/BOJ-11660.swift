import Foundation

// ============================================
// 💡 핵심 아이디어
// ============================================
/// 1. 핵심 아이디어
///     1024*1024 사이즈. 연산은 최대 1e5
///     1. dp[y][x] 정의
///         (x1, y1)부터 (x2, y2)까지의 합
///     2. x, y의 전이
///         x + 1, y
///         x > n -> y+1
///
///         누적합 공부 후:
///         [a][b]
///         [c][d]
///         이 이차원 배열이 있다고 하자.
///
///         1, 1부터 2, 2까지 더한값을 알고 싶다.
///         dp[1][1] = a
///         dp[1][2] = a + b = map[1][2] + dp[i][k-1]
///         dp[2][1] = a + c = map[i-1][j] + map[2][1]
///         dp[2][2] = (a+b) + (a+c) - a = dp[i-1][j] + dp[i][j-1] -  dp[i-1][j-1] + map[i][j]
///
///         다만, dp[i-1][j-1]이 중복이 되므로 한번 빼줘야함.
///
///         dp[i][j] = dp[i-1][j] + dp[i][j-1] - dp[i-1][j-1] + map[i][j]
///     3. 점화식
///         y1
///         x < n: dp[y][x] = dp[y][x-1] + map[y][x]
///         x > n: continue
///         y2
///         x == x2: dp[y][x] = dp[y-1][x1] + map[y][x]
///         x < n: dp[y][x] = dp[y][x-1] + map[y][x]
///
///         누적합 공부 후:
///         단일 좌표가 아닌 이중 좌표에서는...
///         dp[i][j] = dp[i-1][j] + dp[i][j-1] - dp[i-1][j-1] + map[i][j]
///           sum = dp[y2][x2]
///                 - dp[y1-1][x2]
///                 - dp[y2][x1-1]
///                 + dp[y1-1][x1-1]
///     4. 초기값
///         dp[y1][x1] = map[y1][x1]
///
///         누적합 공부 후:
///         dp[0][*] = 0, dp[*][0] = 0
///
/// 2. 자료구조
///     dp[[Int]]
///     map[[Int]]
///     points[[Int]]
///
///     누적합 공부 후:
///     dp[[Int]]
///     map[[Int]]
/// 3. 시간 복잡도
///     O(N^2)
///
///     누적합 공부 후:
///     O(N^2): DP
///     O(M): 각 좌표 처리
///     => O(N^2 + M)
///
// ============================================
// 📌 주의사항
// ============================================

// ============================================
// 🔨 구현
// ============================================

func solution() {
    let input = readLine()!.split(separator: " ").map { Int($0)! }
    let n = input[0]; let m = input[1]
    
    var map = Array(repeating: [Int](), count: n+1)
    
    for i in 1...n {
        var s = [0]
        s.append(contentsOf: readLine()!.split(separator: " ").map { Int($0)! })
        map[i] = s
    }
    
    var dp = Array(repeating: Array(repeating: 0, count: n+1), count: n+1)
    
    for y in 1...n {
        for x in 1...n {
            dp[y][x] = dp[y-1][x] + dp[y][x-1] - dp[y-1][x-1] + map[y][x]
        }
    }
    
    for i in 0..<m {
        let input = readLine()!.split(separator: " ").map { Int($0)! }
        let y1 = input[0]
        let x1 = input[1]
        let y2 = input[2]
        let x2 = input[3]
        
        print(dp[y2][x2] - dp[y1-1][x2] - dp[y2][x1-1] + dp[y1-1][x1-1])
    }
}

solution()

